CREATE TABLE SYSDBA.X1_FUSION_POLICY_RELATION (
  ID BIGINT PRIMARY KEY,
  PARENT_FUSION_POLICY_ID BIGINT NOT NULL,
  CHILD_FUSION_POLICY_ID BIGINT NOT NULL,
  DEL_FLAG CHAR(1) DEFAULT '0',
  CREATED_BY VARCHAR2(100),
  UPDATED_BY VARCHAR2(100),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_X1_FUSION_REL_CHILD
  ON SYSDBA.X1_FUSION_POLICY_RELATION (CHILD_FUSION_POLICY_ID, DEL_FLAG);

CREATE INDEX IDX_X1_FUSION_REL_PARENT
  ON SYSDBA.X1_FUSION_POLICY_RELATION (PARENT_FUSION_POLICY_ID, DEL_FLAG);

COMMENT ON TABLE SYSDBA.X1_FUSION_POLICY_RELATION IS '融合主政策直接父子关系表（支持一个主政策关联多个上级和多个下级）';
COMMENT ON COLUMN SYSDBA.X1_FUSION_POLICY_RELATION.PARENT_FUSION_POLICY_ID IS '上级主政策ID（可为同一下级主政策配置多条）';
COMMENT ON COLUMN SYSDBA.X1_FUSION_POLICY_RELATION.CHILD_FUSION_POLICY_ID IS '下级主政策ID（可为同一上级主政策配置多条）';
COMMENT ON COLUMN SYSDBA.X1_FUSION_POLICY_RELATION.CREATED_BY IS '创建操作人';
COMMENT ON COLUMN SYSDBA.X1_FUSION_POLICY_RELATION.UPDATED_BY IS '最后更新操作人';
