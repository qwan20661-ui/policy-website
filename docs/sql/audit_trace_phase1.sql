-- 二、统一审计日志表
-- =========================================================

CREATE TABLE SYSDBA.OPERATION_AUDIT_LOG (
  ID VARCHAR2(36) PRIMARY KEY,
  TRACE_ID VARCHAR2(64),
  MODULE VARCHAR2(100),
  ACTION VARCHAR2(50),
  TARGET_TABLE VARCHAR2(100),
  TARGET_ID VARCHAR2(100),
  BIZ_KEY VARCHAR2(200),
  OPERATOR_ID VARCHAR2(100),
  OPERATOR_NAME VARCHAR2(100),
  BEFORE_JSON CLOB,
  AFTER_JSON CLOB,
  REMARK VARCHAR2(1000),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_OP_AUDIT_TRACE_ID
  ON SYSDBA.OPERATION_AUDIT_LOG (TRACE_ID);

CREATE INDEX IDX_OP_AUDIT_TARGET
  ON SYSDBA.OPERATION_AUDIT_LOG (TARGET_TABLE, TARGET_ID);

CREATE INDEX IDX_OP_AUDIT_OPERATOR
  ON SYSDBA.OPERATION_AUDIT_LOG (OPERATOR_NAME, CREATED_AT);

CREATE INDEX IDX_OP_AUDIT_MODULE
  ON SYSDBA.OPERATION_AUDIT_LOG (MODULE, ACTION, CREATED_AT);

COMMENT ON TABLE SYSDBA.OPERATION_AUDIT_LOG IS '前端写库统一审计日志表';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.ID IS '主键 UUID';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.TRACE_ID IS '一次前端操作的链路 ID';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.MODULE IS '模块名，如 base-data';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.ACTION IS '操作类型，如 create、update、delete、clear';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.TARGET_TABLE IS '目标表名';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.TARGET_ID IS '目标记录主键';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.BIZ_KEY IS '业务主键或分类标识';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.OPERATOR_ID IS '操作人 ID';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.OPERATOR_NAME IS '操作人姓名或用户名';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.BEFORE_JSON IS '修改前快照';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.AFTER_JSON IS '修改后快照';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.REMARK IS '审计备注';
COMMENT ON COLUMN SYSDBA.OPERATION_AUDIT_LOG.CREATED_AT IS '日志写入时间';

