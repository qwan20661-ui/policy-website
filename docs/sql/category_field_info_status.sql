-- CATEGORY_FIELD_INFO status column migration
-- STATUS: 1 = enabled, 0 = disabled

DECLARE
    V_COUNT INT;
BEGIN
    SELECT COUNT(1) INTO V_COUNT
      FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'SYSDBA'
       AND TABLE_NAME = 'CATEGORY_FIELD_INFO'
       AND COLUMN_NAME = 'STATUS';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SYSDBA.CATEGORY_FIELD_INFO ADD STATUS NUMBER(3) DEFAULT 1 NOT NULL';
    END IF;
END;
/

COMMENT ON COLUMN SYSDBA.CATEGORY_FIELD_INFO.STATUS IS '状态：1启用，0禁用';

