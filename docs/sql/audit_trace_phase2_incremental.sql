DECLARE
    V_COUNT INT;
BEGIN
    SELECT COUNT(1) INTO V_COUNT
      FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'SYSDBA'
       AND TABLE_NAME = 'POLICY_METADATA'
       AND COLUMN_NAME = 'CREATED_AT';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SYSDBA.POLICY_METADATA ADD CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP';
    END IF;
END;
/

