-- PEMatching 企业政策匹配运行结果表
-- 适用数据库：达梦 DM8
-- 执行方式：由数据库管理员手工执行一次；本脚本不包含删除或清空操作

CREATE TABLE SYSDBA.PEM_ENTERPRISE_MATCH_RUN (
  RUN_ID VARCHAR2(32) PRIMARY KEY,
  ENTERPRISE_ID VARCHAR2(100) NOT NULL,
  ENTERPRISE_NAME VARCHAR2(500) NOT NULL,
  CREDIT_CODE VARCHAR2(64),
  POLICY_COUNT INTEGER DEFAULT 0 NOT NULL,
  RESPONSE_JSON CLOB NOT NULL,
  DETAIL_FILE_NAME VARCHAR2(1000) NOT NULL,
  DETAIL_FILE_SIZE BIGINT DEFAULT 0 NOT NULL,
  SCHEMA_VERSION VARCHAR2(64) DEFAULT 'enterprise-match-detail-v1' NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX SYSDBA.IDX_PEM_EMR_ENTERPRISE_TIME
  ON SYSDBA.PEM_ENTERPRISE_MATCH_RUN (ENTERPRISE_ID, CREATED_AT);

CREATE INDEX SYSDBA.IDX_PEM_EMR_CREATED_AT
  ON SYSDBA.PEM_ENTERPRISE_MATCH_RUN (CREATED_AT);

COMMENT ON TABLE SYSDBA.PEM_ENTERPRISE_MATCH_RUN IS 'PEMatching 企业政策匹配运行结果，一次运行一条记录';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.RUN_ID IS '匹配运行唯一标识，与接口 meta.runId 一致';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.ENTERPRISE_ID IS '上游企业分页接口返回的企业 ID';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.ENTERPRISE_NAME IS '匹配运行时企业名称快照';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.CREDIT_CODE IS '匹配运行时统一社会信用代码快照';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.POLICY_COUNT IS '本次匹配政策数量';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.RESPONSE_JSON IS '公开接口 data 对象 JSON，结构为 policies 数组';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.DETAIL_FILE_NAME IS 'output 归档目录中的完整跑数文件名，不保存绝对路径';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.DETAIL_FILE_SIZE IS '完整跑数归档文件字节数';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.SCHEMA_VERSION IS '完整跑数归档文件结构版本';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.CREATED_AT IS '数据库入库时间，用于选择企业最新结果';

COMMIT;

-- 验证表结构
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'PEM_ENTERPRISE_MATCH_RUN'
ORDER BY COLUMN_ID;

-- 验证指定企业的最新结果
SELECT RUN_ID, ENTERPRISE_ID, ENTERPRISE_NAME, CREDIT_CODE, POLICY_COUNT, CREATED_AT
FROM (
  SELECT RUN_ID, ENTERPRISE_ID, ENTERPRISE_NAME, CREDIT_CODE, POLICY_COUNT, CREATED_AT
  FROM SYSDBA.PEM_ENTERPRISE_MATCH_RUN
  WHERE ENTERPRISE_ID = '请替换为企业ID'
  ORDER BY CREATED_AT DESC, RUN_ID DESC
)
WHERE ROWNUM = 1;

-- 验证每个企业只取最新一次运行
SELECT ENTERPRISE_ID, ENTERPRISE_NAME, CREDIT_CODE, RUN_ID, POLICY_COUNT, CREATED_AT
FROM (
  SELECT r.*,
         ROW_NUMBER() OVER (
           PARTITION BY ENTERPRISE_ID
           ORDER BY CREATED_AT DESC, RUN_ID DESC
         ) AS RN
  FROM SYSDBA.PEM_ENTERPRISE_MATCH_RUN r
)
WHERE RN = 1
ORDER BY CREATED_AT DESC;
