-- PEMatching 企业政策匹配结果表轻量化迁移
-- 适用场景：已经执行过包含 DETAIL_JSON CLOB NOT NULL 的旧版建表脚本
-- 适用数据库：达梦 DM8
-- 执行方式：停止 8010 写入后，由数据库管理员手工执行一次
-- 本脚本不删除 DETAIL_JSON，不删除历史数据；新版本服务不再写入该列

ALTER TABLE SYSDBA.PEM_ENTERPRISE_MATCH_RUN
  ADD DETAIL_FILE_NAME VARCHAR2(1000);

ALTER TABLE SYSDBA.PEM_ENTERPRISE_MATCH_RUN
  ADD DETAIL_FILE_SIZE BIGINT DEFAULT 0 NOT NULL;

ALTER TABLE SYSDBA.PEM_ENTERPRISE_MATCH_RUN
  MODIFY (DETAIL_JSON NULL);

COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.DETAIL_FILE_NAME IS 'output 归档目录中的完整跑数文件名，不保存绝对路径';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.DETAIL_FILE_SIZE IS '完整跑数归档文件字节数';
COMMENT ON COLUMN SYSDBA.PEM_ENTERPRISE_MATCH_RUN.DETAIL_JSON IS '历史完整跑数 JSON；新版本停止写入，仅保留旧数据';

COMMIT;

-- 验证迁移后的字段和可空约束
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'PEM_ENTERPRISE_MATCH_RUN'
  AND COLUMN_NAME IN ('RESPONSE_JSON', 'DETAIL_JSON', 'DETAIL_FILE_NAME', 'DETAIL_FILE_SIZE')
ORDER BY COLUMN_ID;

-- 验证新版本写入的轻量记录与归档关联信息
SELECT RUN_ID, ENTERPRISE_ID, POLICY_COUNT, DETAIL_FILE_NAME, DETAIL_FILE_SIZE, CREATED_AT
FROM SYSDBA.PEM_ENTERPRISE_MATCH_RUN
WHERE DETAIL_FILE_NAME IS NOT NULL
ORDER BY CREATED_AT DESC;
