CREATE INDEX IDX_APP_COND_DICT_LEVEL3 ON SYSDBA.APPLICATION_CONDITION_DICT(LEVEL3);
CREATE INDEX IDX_APP_COND_DICT_STATUS ON SYSDBA.APPLICATION_CONDITION_DICT(STATUS);
