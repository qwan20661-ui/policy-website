-- 创建基础数据字典表
CREATE TABLE SYSDBA.BASE_DATA_DICT (
    ID          VARCHAR2(36)   NOT NULL,
    TYPE        VARCHAR2(50)   NOT NULL,
    LEVEL1      VARCHAR2(100)  DEFAULT '',
    LEVEL2      VARCHAR2(100)  DEFAULT '',
    NAME        VARCHAR2(200)  NOT NULL,
    CODE        VARCHAR2(100)  DEFAULT '',
    DESCRIPTION VARCHAR2(1000) DEFAULT '',
    STATUS      VARCHAR2(20)   DEFAULT '启用',
    CREATE_TIME TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
);

-- 为 BASE_DATA_DICT 表创建索引
CREATE INDEX IDX_BASE_DATA_DICT_TYPE ON SYSDBA.BASE_DATA_DICT(TYPE);
CREATE INDEX IDX_BASE_DATA_DICT_LEVEL1 ON SYSDBA.BASE_DATA_DICT(LEVEL1);
CREATE INDEX IDX_BASE_DATA_DICT_LEVEL2 ON SYSDBA.BASE_DATA_DICT(LEVEL2);
CREATE INDEX IDX_BASE_DATA_DICT_STATUS ON SYSDBA.BASE_DATA_DICT(STATUS);
CREATE INDEX IDX_BASE_DATA_DICT_CODE ON SYSDBA.BASE_DATA_DICT(CODE);

-- =============================================================
-- 2. 申报条件字典表 (APPLICATION_CONDITION_DICT)
-- =============================================================

-- 创建申报条件字典表
