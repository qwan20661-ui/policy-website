-- Markdown 政策结构化单表
-- 适用数据库：达梦 DM8
-- 说明：独立保存 Markdown 解析后的字段，不关联 POLICY、POLICY_ATTACHMENT 等现有表。

CREATE TABLE SYSDBA.POLICY_MD_STRUCTURED (
  ID VARCHAR2(36) PRIMARY KEY,

  SOURCE_MD_PATH VARCHAR2(1000) NOT NULL,
  SOURCE_FILE_NAME VARCHAR2(500) NOT NULL,
  CONTENT_HASH VARCHAR2(64),

  POLICY_TITLE VARCHAR2(500) NOT NULL,
  POLICY_LEVEL VARCHAR2(100),
  PUBLISH_REGION VARCHAR2(100),
  POLICY_BATCH VARCHAR2(100),
  ISSUE_DEPARTMENT VARCHAR2(500),
  APPLICANT_OBJECT VARCHAR2(200),
  SUBSIDY_OBJECT VARCHAR2(200),
  INDUSTRY_CATEGORY VARCHAR2(1000),
  ENTERPRISE_SCALE VARCHAR2(100),
  DECLARE_TYPE VARCHAR2(100),
  SUPPORT_METHOD VARCHAR2(100),
  FILE_BASIS VARCHAR2(1000),

  DECLARE_START_TIME TIMESTAMP,
  DECLARE_END_TIME TIMESTAMP,
  ORIGINAL_URL VARCHAR2(2000),

  APPLICATION_CONDITION CLOB,
  SUPPORT_CONTENT CLOB,
  APPLICATION_PROCESS CLOB,
  APPLICATION_MATERIALS CLOB,
  CONTACT_INFO CLOB,
  ATTACHMENTS_JSON CLOB,

  DEL_FLAG CHAR(1) DEFAULT '0' NOT NULL,
  CREATED_BY VARCHAR2(100),
  UPDATED_BY VARCHAR2(100),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX SYSDBA.IDX_POLICY_MD_STRUCT_PATH
  ON SYSDBA.POLICY_MD_STRUCTURED (SOURCE_MD_PATH);

CREATE INDEX SYSDBA.IDX_POLICY_MD_STRUCT_TITLE
  ON SYSDBA.POLICY_MD_STRUCTURED (POLICY_TITLE);

CREATE INDEX SYSDBA.IDX_POLICY_MD_STRUCT_HASH
  ON SYSDBA.POLICY_MD_STRUCTURED (CONTENT_HASH);

CREATE INDEX SYSDBA.IDX_POLICY_MD_STRUCT_CREATED
  ON SYSDBA.POLICY_MD_STRUCTURED (CREATED_AT);

CREATE TABLE SYSDBA.STRUCTURED_ATTACHMENT (
  ID VARCHAR2(36) PRIMARY KEY,
  STRUCTURED_ID VARCHAR2(36) NOT NULL,
  SOURCE_MD_PATH VARCHAR2(1000) NOT NULL,
  ATTACH_NAME VARCHAR2(500) NOT NULL,
  ATTACH_SHOW_NAME VARCHAR2(500),
  MARKDOWN_RELATIVE_PATH VARCHAR2(1000) NOT NULL,
  FILE_PATH VARCHAR2(1000) NOT NULL,
  FILE_SUFFIX VARCHAR2(30),
  FILE_SIZE BIGINT DEFAULT 0 NOT NULL,
  CONTENT_HASH VARCHAR2(64),
  DEL_FLAG CHAR(1) DEFAULT '0' NOT NULL,
  CREATED_BY VARCHAR2(100),
  UPDATED_BY VARCHAR2(100),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_STRUCT_ATTACH_STRUCTURED
    FOREIGN KEY (STRUCTURED_ID) REFERENCES SYSDBA.POLICY_MD_STRUCTURED(ID)
);

CREATE INDEX SYSDBA.IDX_STRUCT_ATTACH_STRUCTURED
  ON SYSDBA.STRUCTURED_ATTACHMENT (STRUCTURED_ID, DEL_FLAG);

CREATE INDEX SYSDBA.IDX_STRUCT_ATTACH_FILE_PATH
  ON SYSDBA.STRUCTURED_ATTACHMENT (FILE_PATH);

CREATE INDEX SYSDBA.IDX_STRUCT_ATTACH_HASH
  ON SYSDBA.STRUCTURED_ATTACHMENT (CONTENT_HASH);

COMMENT ON TABLE SYSDBA.POLICY_MD_STRUCTURED IS 'Markdown 政策结构化单表';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.ID IS '主键 UUID';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.SOURCE_MD_PATH IS 'Markdown 文件相对路径';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.SOURCE_FILE_NAME IS 'Markdown 文件名';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.CONTENT_HASH IS 'Markdown 文件内容 SHA-256，用于导入去重';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.POLICY_TITLE IS '政策标题';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.POLICY_LEVEL IS '政策层级';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.PUBLISH_REGION IS '发布地区';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.POLICY_BATCH IS '政策批次';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.ISSUE_DEPARTMENT IS '主管部门';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.APPLICANT_OBJECT IS '申请对象';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.SUBSIDY_OBJECT IS '补贴对象';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.INDUSTRY_CATEGORY IS '行业类别';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.ENTERPRISE_SCALE IS '企业规模';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.DECLARE_TYPE IS '申报类型';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.SUPPORT_METHOD IS '支持方式';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.FILE_BASIS IS '文件依据';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.DECLARE_START_TIME IS '申报开始时间';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.DECLARE_END_TIME IS '申报结束时间';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.ORIGINAL_URL IS '政策原文链接';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.APPLICATION_CONDITION IS '申报条件，按分点保留换行';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.SUPPORT_CONTENT IS '扶持内容';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.APPLICATION_PROCESS IS '申报流程，按分点保留换行';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.APPLICATION_MATERIALS IS '申报材料，按分点保留换行';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.CONTACT_INFO IS '咨询电话和联系方式';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.ATTACHMENTS_JSON IS '附件 JSON，包含附件名称、相对路径和后缀';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.DEL_FLAG IS '删除标记：0=正常，1=删除';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.CREATED_BY IS '创建操作人';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.UPDATED_BY IS '最后更新操作人';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.CREATED_AT IS '创建时间';
COMMENT ON COLUMN SYSDBA.POLICY_MD_STRUCTURED.UPDATED_AT IS '更新时间';

COMMENT ON TABLE SYSDBA.STRUCTURED_ATTACHMENT IS 'Markdown 政策结构化附件表';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.ID IS '主键 UUID';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.STRUCTURED_ID IS '关联 POLICY_MD_STRUCTURED.ID';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.SOURCE_MD_PATH IS '来源 Markdown 文件相对路径';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.ATTACH_NAME IS '附件文件名';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.ATTACH_SHOW_NAME IS 'Markdown 中展示的附件名称';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.MARKDOWN_RELATIVE_PATH IS 'Markdown 链接中的附件相对路径';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.FILE_PATH IS '附件文件在工作区内的相对路径';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.FILE_SUFFIX IS '附件后缀';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.FILE_SIZE IS '附件文件字节数';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.CONTENT_HASH IS '附件内容 SHA-256，用于附件去重检查';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.DEL_FLAG IS '删除标记：0=正常，1=删除';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.CREATED_BY IS '创建操作人';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.UPDATED_BY IS '最后更新操作人';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.CREATED_AT IS '创建时间';
COMMENT ON COLUMN SYSDBA.STRUCTURED_ATTACHMENT.UPDATED_AT IS '更新时间';

COMMIT;

SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'POLICY_MD_STRUCTURED'
ORDER BY COLUMN_ID;

SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'STRUCTURED_ATTACHMENT'
ORDER BY COLUMN_ID;
